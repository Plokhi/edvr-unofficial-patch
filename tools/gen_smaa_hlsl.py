#!/usr/bin/env python3
"""Turn the vendored SMAA.hlsl into HLSL string chunks the DLL can embed.

WHY CHUNKS. A single MSVC string literal is capped at 65535 bytes and
SMAA.hlsl is 56 KB with escaping, so it cannot be one literal. The same shape
gen_fsr_hlsl.py uses for AMD's FSR: an array of chunks joined at run time.

WHY BYTES, NOT TEXT. SMAA.hlsl is the upstream file, byte for byte, with CRLF
line endings and two 0xB7 bytes inside comments. Every byte is written out: a
byte outside printable ASCII becomes a three-digit octal escape, so the text
the compiler sees is exactly the file. Only comments carry those bytes.

PINNED. The source must hash to PINNED_SHA256 (the vendored commit, see
src/d3d11/smaa/README.md). A changed file fails here, before anything is
written, so a local edit cannot ship under the upstream name. A newer SMAA is a
file swap plus a new pin.

Usage:  python tools/gen_smaa_hlsl.py --root ROOT --out DIR [--dry-run]
        python tools/gen_smaa_hlsl.py --self-test
Writes: DIR/smaa_hlsl_gen.h

--dry-run checks the source and reports the file it would write, writing
nothing (not the directory either). --self-test runs the escaping and the
chunking over fixtures in the temp folder and checks that the chunks read back
to the same bytes; build.bat runs it before it trusts the tool.
"""

import argparse
import hashlib
import io
import os
import sys
import tempfile

# Raw bytes per chunk. Each chunk is escaped on its own; the worst escape is
# four characters per byte, so a chunk stays well under the 65535-byte cap.
CHUNK = 12000

SOURCE = os.path.join('src', 'd3d11', 'smaa', 'SMAA.hlsl')
# SHA-256 of the vendored SMAA.hlsl at upstream commit 71c806a8 (src/d3d11/smaa/README.md).
PINNED_SHA256 = '4db53d92ef0b45661f8450303589ffabce93c352cae4282a6f32dd2b80efbeb9'


def escape(data):
    out = []
    for b in data:
        ch = chr(b)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif ch == '?':
            # Trigraph guard, as in gen_fsr_hlsl.py.
            out.append('\\?')
        elif 32 <= b < 127:
            out.append(ch)
        else:
            # Always three octal digits, so the next character cannot extend it.
            out.append('\\%03o' % b)
    return ''.join(out)


def chunks_of(data):
    return [data[i:i + CHUNK] for i in range(0, len(data), CHUNK)] or [b'']


def render(data, expected_sha256=PINNED_SHA256):
    """The whole generated header, as text. Raises SystemExit on a source that
    does not match the pin, before anything has been written."""
    digest = hashlib.sha256(data).hexdigest()
    if expected_sha256 is not None and digest != expected_sha256:
        raise SystemExit('SMAA.hlsl does not match its pin: sha256 %s, expected %s' % (digest, expected_sha256))
    fh = io.StringIO()
    fh.write('// GENERATED by tools/gen_smaa_hlsl.py -- do not edit.\n')
    fh.write('//\n')
    fh.write('// SMAA 1x, verbatim from src/d3d11/smaa/SMAA.hlsl (Jorge Jimenez et al., MIT;\n')
    fh.write('// upstream commit 71c806a8). The notice travels with the text below.\n')
    fh.write('#pragma once\n\n')
    fh.write('namespace edvr {\n\n')
    fh.write('inline const char* const kSmaaChunks[] = {\n')
    for c in chunks_of(data):
        fh.write('    "%s",\n' % escape(c))
    fh.write('    nullptr,\n};\n\n')
    fh.write('}  // namespace edvr\n')
    return fh.getvalue()


# ---------------------------------------------------------------------------
# --self-test
# ---------------------------------------------------------------------------

def unescape_literal(text):
    """Read back one escaped literal body (the inside of the quotes)."""
    out = bytearray()
    i = 0
    while i < len(text):
        c = text[i]
        if c != '\\':
            out.append(ord(c))
            i += 1
            continue
        n = text[i + 1]
        if n in '01234567':
            out.append(int(text[i + 1:i + 4], 8))
            i += 4
            continue
        table = {'\\': 0x5C, '"': 0x22, 'n': 0x0A, 'r': 0x0D, 't': 0x09, '?': 0x3F}
        out.append(table[n])
        i += 2
    return bytes(out)


def read_back(header):
    """The chunks as bytes, in order, parsed from the generated header."""
    body = header[header.index('kSmaaChunks[] = {') + len('kSmaaChunks[] = {'):]
    parts = []
    for line in body.split('\n'):
        s = line.strip()
        if s == 'nullptr,':
            break
        if s.startswith('"') and s.endswith('",'):
            parts.append(unescape_literal(s[1:-2]))
    return parts


def self_test():
    failures = []

    def expect(name, ok, detail=''):
        if not ok:
            failures.append('%s %s' % (name, detail))

    # A fixture with every awkward byte: CRLF, a 0xB7 in a comment, quotes, a
    # backslash, a trigraph start, a NUL, and enough length to need two chunks.
    raw = b'// comment \xb7 here\r\n#define X "q" \\ ??/ \x00 1\r\n'
    raw = raw + bytes((i * 37) % 256 for i in range(CHUNK + 500))
    pin = hashlib.sha256(raw).hexdigest()
    header = render(raw, pin)
    expect('header', header.startswith('// GENERATED by tools/gen_smaa_hlsl.py -- do not edit.\n'), header[:60])
    expect('chunk array', 'kSmaaChunks[] = {' in header and header.rstrip().endswith('}  // namespace edvr'))
    parts = read_back(header)
    expect('chunk count', len(parts) == 2, repr(len(parts)))
    expect('round trip', b''.join(parts) == raw, 'bytes differ')
    expect('no raw non-ASCII', all(ord(ch) < 128 for ch in header), 'non-ASCII in header')
    expect('octal for 0xb7', '\\267' in header, 'missing \\267')

    # The pin refuses a changed source before anything is written.
    try:
        render(raw + b'x', pin)
        expect('pin refuses', False, 'a changed source rendered')
    except SystemExit:
        pass

    # --dry-run writes nothing, not even the directory.
    with tempfile.TemporaryDirectory() as tmp:
        root = os.path.join(tmp, 'root')
        os.makedirs(os.path.join(root, 'src', 'd3d11', 'smaa'))
        with open(os.path.join(root, SOURCE), 'wb') as f:
            f.write(raw)
        out = os.path.join(tmp, 'gen')
        rc = main(['--root', root, '--out', out, '--dry-run'], pin_override=pin)
        expect('dry run', rc == 0 and not os.path.exists(out), 'dry run wrote something')
        rc = main(['--root', root, '--out', out], pin_override=pin)
        written = os.path.join(out, 'smaa_hlsl_gen.h')
        expect('real run', rc == 0 and os.path.exists(written), 'no output written')
        if os.path.exists(written):
            with open(written, encoding='ascii') as f:
                expect('written round trip', b''.join(read_back(f.read())) == raw, 'written bytes differ')

    if failures:
        for f in failures:
            sys.stderr.write('gen_smaa_hlsl self-test: %s\n' % f)
        print('gen_smaa_hlsl: self-test FAILED')
        return 1
    print('gen_smaa_hlsl: self-test OK')
    return 0


def main(argv=None, pin_override=PINNED_SHA256):
    ap = argparse.ArgumentParser()
    ap.add_argument('--root')
    ap.add_argument('--out')
    ap.add_argument('--dry-run', action='store_true',
                    help='say what would be written and write nothing')
    ap.add_argument('--self-test', action='store_true',
                    help='check this script against fixtures and exit')
    args = ap.parse_args(argv)
    if args.self_test:
        return self_test()
    if not args.root or not args.out:
        ap.error('--root and --out are required')

    path_src = os.path.join(args.root, SOURCE)
    if not os.path.exists(path_src):
        sys.stderr.write('missing vendored SMAA source: %s\n' % SOURCE)
        return 1
    with open(path_src, 'rb') as f:
        data = f.read()

    text = render(data, pin_override)
    path = os.path.join(args.out, 'smaa_hlsl_gen.h')
    if args.dry_run:
        print('[edvr] dry run: would generate %s (%d bytes); wrote nothing' % (path, len(text)))
        return 0
    os.makedirs(args.out, exist_ok=True)
    with open(path, 'w', encoding='ascii', newline='\n') as fh:
        fh.write(text)
    print('[edvr] generated %s' % path)
    return 0


if __name__ == '__main__':
    sys.exit(main())
